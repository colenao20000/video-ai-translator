class I18n:
    _current_lang: str = LanguageCode.VI

    @classmethod
    def set_language(cls, lang: LanguageCode) -> None:
        cls._current_lang = lang

    @classmethod
    def get_language(cls) -> str:
        return cls._current_lang

    @classmethod
    def tr(cls, key: str, **kwargs) -> str:
        lang_dict = TRANSLATIONS.get(cls._current_lang, TRANSLATIONS[LanguageCode.VI])
        template = lang_dict.get(key)
        if template is None:
            template = TRANSLATIONS[LanguageCode.VI].get(key, key)
        if kwargs:
            try:
                return template.format(**kwargs)
            except Exception:
                return template
        return template


def tr(key: str, **kwargs) -> str:
    return I18n.tr(key, **kwargs)
